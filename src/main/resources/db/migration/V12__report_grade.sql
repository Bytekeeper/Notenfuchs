-- A report-card grade a teacher set by hand ("Zeugnisnote"), shown instead of the computed final
-- grade. The computed grade stays live next to it; this row only records the teacher's decision.
CREATE TABLE report_grade (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES student(id) ON DELETE CASCADE,
    subject_id BIGINT NOT NULL REFERENCES subject(id) ON DELETE CASCADE,
    period     VARCHAR(16)  NOT NULL,
    value      NUMERIC(4,2) NOT NULL,
    UNIQUE (student_id, subject_id, period)
);

CREATE INDEX idx_report_grade_subject ON report_grade(subject_id);
CREATE SEQUENCE report_grade_seq START WITH 1 INCREMENT BY 50;
