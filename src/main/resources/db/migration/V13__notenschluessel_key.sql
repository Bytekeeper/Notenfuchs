-- A Notenschlüssel is read against a test's maximum points, either as steps ("ab 35 Punkten eine 1")
-- or sliding (the grade moves evenly between two rows). Existing keys were sliding, so they keep
-- that and every grade stays as it was; their highest row becomes the maximum.
ALTER TABLE assessment ADD COLUMN max_points NUMERIC(6,2);
ALTER TABLE assessment ADD COLUMN points_sliding BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE assessment a
SET points_sliding = TRUE,
    max_points = (SELECT MAX(b.points) FROM points_grade_band b WHERE b.assessment_id = a.id)
WHERE a.points_based;
-- A sliding grade is always rounded to one decimal in the student's favor.
ALTER TABLE assessment DROP COLUMN rounding_mode;

-- A Fach's key as percentages of the maximum; no rows means the computed default.
CREATE TABLE subject_points_key (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id  BIGINT NOT NULL REFERENCES subject(id) ON DELETE CASCADE,
    grade_value NUMERIC(4,2) NOT NULL,
    min_percent NUMERIC(5,2) NOT NULL,
    UNIQUE (subject_id, grade_value)
);
CREATE INDEX idx_subject_points_key_subject ON subject_points_key(subject_id);
CREATE SEQUENCE subject_points_key_seq START WITH 1 INCREMENT BY 50;
ALTER TABLE subject ADD COLUMN points_key_sliding BOOLEAN NOT NULL DEFAULT FALSE;

